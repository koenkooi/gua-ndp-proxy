#!/bin/bash
# SPDX-License-Identifier: MIT
# usb-gadget-subnet IFNAME
#
# Run by udev for each new USB gadget-ethernet interface. Writes a
# systemd-networkd config giving the interface its own private IPv4 /24 (so
# several gadget devices can be attached at once) and, if GUA_PREFIX is set,
# the off-link router advertisement gua-ndp-proxy needs.
set -euo pipefail

CONF_FILE=${GADGET_SUBNET_CONF:-/etc/gua-ndp-proxy/gadget-subnet.conf}
NETWORKD_DIR=${GADGET_SUBNET_NETWORKD_DIR:-/etc/systemd/network}
SYSFS_NET=${GADGET_SUBNET_SYSFS:-/sys/class/net}

# Defaults, overridable in CONF_FILE (a root-owned shell fragment).
# Private subnets are 192.168.<SUBNET_BASE>..<SUBNET_BASE+SUBNET_SPAN-1>.0/24.
SUBNET_BASE=160
SUBNET_SPAN=80
GUA_PREFIX=""   # the delegated /64, e.g. 2001:db8:1234:5678::/64
GUA_DNS6=""     # IPv6 resolver to advertise, optional

die() { echo "usb-gadget-subnet: $*" >&2; exit 1; }

IFNAME=${1:-}
[[ $IFNAME =~ ^[A-Za-z0-9_.:-]{1,15}$ ]] || die "invalid interface name"

# shellcheck source=/dev/null
[[ -r $CONF_FILE ]] && . "$CONF_FILE"

[[ $SUBNET_BASE =~ ^[0-9]+$ && $SUBNET_SPAN =~ ^[0-9]+$ ]] \
    || die "SUBNET_BASE and SUBNET_SPAN must be numbers"
(( SUBNET_BASE >= 1 && SUBNET_SPAN >= 1 && SUBNET_BASE + SUBNET_SPAN <= 255 )) \
    || die "subnet range must fit within 192.168.1-254.0/24"
[[ -z $GUA_PREFIX || $GUA_PREFIX =~ ^[0-9a-fA-F:]+/64$ ]] \
    || die "GUA_PREFIX must be a /64"
[[ -z $GUA_DNS6 || $GUA_DNS6 =~ ^[0-9a-fA-F:]+$ ]] || die "invalid GUA_DNS6"

IFINDEX=$(cat "$SYSFS_NET/$IFNAME/ifindex" 2>/dev/null) || exit 0
[[ $IFINDEX =~ ^[0-9]+$ ]] || exit 0

# Third octets already taken by other live interfaces, whether configured on
# the link or by an existing config file of an interface that still exists.
declare -A used=()
while read -r _ dev _ cidr _; do
    [[ $dev == "$IFNAME" ]] && continue
    [[ $cidr =~ ^192\.168\.([0-9]+)\. ]] && used[${BASH_REMATCH[1]}]=1
done < <(ip -4 -o addr show 2>/dev/null || true)
for f in "$NETWORKD_DIR"/05-usb-gadget-*.network; do
    [[ -e $f ]] || continue
    other=${f##*/05-usb-gadget-}; other=${other%.network}
    [[ $other == "$IFNAME" || ! -d $SYSFS_NET/$other ]] && continue
    octet=$(sed -n 's/^Address=192\.168\.\([0-9]*\)\..*/\1/p' "$f" | head -n 1)
    [[ -n $octet ]] && used[$octet]=1
done

subnet=""
for ((k = 0; k < SUBNET_SPAN; k++)); do
    cand=$((SUBNET_BASE + (IFINDEX + k) % SUBNET_SPAN))
    if [[ -z ${used[$cand]:-} ]]; then subnet=$cand; break; fi
done
[[ -n $subnet ]] || die "no free subnet in 192.168.$SUBNET_BASE-$((SUBNET_BASE + SUBNET_SPAN - 1)).0/24"

# Hand out the host's real IPv4 resolvers; the local stub (127.*) is not
# reachable from the gadget link.
dns=""
for f in /run/systemd/resolve/resolv.conf /etc/resolv.conf; do
    [[ -r $f ]] || continue
    while read -r key val _; do
        [[ $key == nameserver && $val =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || continue
        [[ $val == 127.* ]] && continue
        dns+="${dns:+ }$val"
    done < "$f"
    [[ -n $dns ]] && break
done

out="$NETWORKD_DIR/05-usb-gadget-$IFNAME.network"
tmp=$(mktemp "$out.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
    echo "# Generated by usb-gadget-subnet for $IFNAME. Recreated when the device is"
    echo "# plugged in again; safe to delete."
    echo
    echo "[Match]"
    echo "Name=$IFNAME"
    echo
    echo "[Link]"
    echo "RequiredForOnline=no"
    echo
    echo "[Network]"
    echo "DHCPServer=yes"
    echo "Address=192.168.$subnet.1/24"
    echo "IPv6AcceptRA=no"
    echo "IPv6Forwarding=yes"
    echo "IPv6SendRA=yes"
    echo "IPMasquerade=both"
    echo "LinkLocalAddressing=ipv6"
    echo
    echo "[DHCPServer]"
    echo "PoolOffset=10"
    echo "PoolSize=40"
    echo "EmitRouter=yes"
    if [[ -n $dns ]]; then
        echo "EmitDNS=yes"
        echo "DNS=$dns"
    else
        echo "EmitDNS=no"
    fi
    echo "DefaultLeaseTimeSec=3600"
    echo "MaxLeaseTimeSec=3600"
    if [[ -n $GUA_DNS6 ]]; then
        echo
        echo "[IPv6SendRA]"
        echo "EmitDNS=yes"
        echo "DNS=$GUA_DNS6"
    fi
    if [[ -n $GUA_PREFIX ]]; then
        echo
        echo "# Off-link: the device SLAACs a global address but keeps routing"
        echo "# through this host. See gua-ndp-proxy."
        echo "[IPv6Prefix]"
        echo "Prefix=$GUA_PREFIX"
        echo "OnLink=no"
        echo "Autonomous=yes"
    fi
} > "$tmp"
chmod 0644 "$tmp"
mv -f "$tmp" "$out"
trap - EXIT

[[ -n ${GADGET_SUBNET_NO_RELOAD:-} ]] || networkctl reload
